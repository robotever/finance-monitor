CREATE TABLE sector_breadth_daily (
    sector_id TEXT NOT NULL,
    market_date TEXT NOT NULL,
    membership_version TEXT NOT NULL,
    catalog_version TEXT NOT NULL,
    membership_mode TEXT NOT NULL CHECK(membership_mode IN ('current_members_backfill', 'point_in_time_snapshot')),
    advancing_count INTEGER CHECK(advancing_count >= 0),
    declining_count INTEGER CHECK(declining_count >= 0),
    unchanged_count INTEGER CHECK(unchanged_count >= 0),
    valid_count INTEGER CHECK(valid_count >= 0),
    total_count INTEGER CHECK(total_count >= 0),
    advancing_share REAL CHECK(advancing_share BETWEEN 0 AND 1),
    declining_share REAL CHECK(declining_share BETWEEN 0 AND 1),
    median_return REAL,
    strong_stock_share REAL CHECK(strong_stock_share BETWEEN 0 AND 1),
    return_dispersion REAL CHECK(return_dispersion >= 0),
    top5_turnover_share REAL CHECK(top5_turnover_share BETWEEN 0 AND 1),
    top1_contribution_share REAL CHECK(top1_contribution_share BETWEEN 0 AND 1),
    volume_expansion_share REAL CHECK(volume_expansion_share BETWEEN 0 AND 1),
    completeness REAL NOT NULL CHECK(completeness BETWEEN 0 AND 1),
    observed_at_ms INTEGER NOT NULL CHECK(observed_at_ms >= 0),
    source TEXT NOT NULL DEFAULT 'Hithink',
    PRIMARY KEY (sector_id, market_date, membership_version),
    FOREIGN KEY (catalog_version, sector_id) REFERENCES sector_catalog
);
