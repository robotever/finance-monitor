CREATE TABLE sector_catalog (
    catalog_version TEXT NOT NULL,
    sector_id TEXT NOT NULL,
    name TEXT NOT NULL CHECK(length(name) > 0),
    tag TEXT NOT NULL CHECK(tag IN ('industry', 'cn_concept', 'region', 'tszs')),
    parent_sector_id TEXT,
    valid_from TEXT,
    valid_to TEXT,
    observed_at_ms INTEGER NOT NULL CHECK(observed_at_ms >= 0),
    source TEXT NOT NULL DEFAULT 'Hithink',
    PRIMARY KEY (catalog_version, sector_id)
);
CREATE TABLE sector_membership_snapshot (
    membership_date TEXT NOT NULL,
    sector_id TEXT NOT NULL,
    stock_id TEXT NOT NULL,
    catalog_version TEXT NOT NULL,
    membership_version TEXT NOT NULL,
    observed_at_ms INTEGER NOT NULL CHECK(observed_at_ms >= 0),
    source TEXT NOT NULL DEFAULT 'Hithink',
    PRIMARY KEY (membership_date, sector_id, stock_id),
    FOREIGN KEY (catalog_version, sector_id) REFERENCES sector_catalog
);
CREATE TABLE sector_index_daily (
    sector_id TEXT NOT NULL,
    market_date TEXT NOT NULL,
    catalog_version TEXT NOT NULL,
    open REAL NOT NULL CHECK(open > 0),
    high REAL NOT NULL CHECK(high > 0),
    low REAL NOT NULL CHECK(low > 0),
    close REAL NOT NULL CHECK(close > 0),
    volume REAL NOT NULL CHECK(volume >= 0),
    turnover REAL NOT NULL CHECK(turnover >= 0),
    observed_at_ms INTEGER CHECK(observed_at_ms >= 0),
    source TEXT NOT NULL DEFAULT 'Hithink',
    PRIMARY KEY (sector_id, market_date),
    FOREIGN KEY (catalog_version, sector_id) REFERENCES sector_catalog
);
