CREATE TABLE ingest_runs (
    run_id TEXT NOT NULL PRIMARY KEY,
    kind TEXT NOT NULL CHECK(kind IN ('catalog', 'membership', 'backfill', 'intraday', 'close')),
    started_at_ms INTEGER NOT NULL CHECK(started_at_ms >= 0),
    finished_at_ms INTEGER CHECK(finished_at_ms >= started_at_ms),
    source_at_ms INTEGER CHECK(source_at_ms >= 0),
    request_count INTEGER NOT NULL DEFAULT 0 CHECK(request_count >= 0),
    elapsed_ms INTEGER CHECK(elapsed_ms >= 0),
    coverage REAL CHECK(coverage BETWEEN 0 AND 1),
    safe_error_code TEXT,
    source TEXT NOT NULL DEFAULT 'Hithink'
);
